#!/usr/bin/env bash
# check_fixture_name_convention.sh — smoke 판정 스위트의 fixture 이름 규약을 강제합니다.
#
# ## 왜 필요한가
#
# smoke 의 관련성 판정은 "변경 파일의 basename 이 어떤 스텝의 참조 폐포 구성원 **본문**에
# 등장하면 그 스텝은 관련 있음" 입니다. 그리고 어떤 스텝의 폐포에도 걸리지 않는 인프라
# 변경이 있으면 full 로 폴백합니다 — 신규 파일을 아무도 검증하지 않는 채 대부분의 스텝을
# 건너뛰는 사태를 막는 마지막 그물입니다.
#
# 그런데 smoke 판정 스위트 자신도 full 스텝으로 등록돼 있어 어떤 폐포의 구성원입니다.
# 그래서 스위트 본문에 **평범한 이름의 fixture** 를 리터럴로 적어 두면, 나중에 같은 이름의
# 실제 인프라 파일이 신설됐을 때 "그 이름은 이미 폐포 본문에 있으니 커버됨" 으로 오판되어
# 그 파일의 무매핑 폴백이 통째로 사라집니다. 이름 하나가 그물에 구멍 하나를 냅니다
# (실측: 흔한 어간의 이름 1개만 추가해도 실행 25 / 스킵 24 로 축소된 채 PASS 했습니다).
#
# 그래서 스위트의 fixture 이름에는 `_zzfx` 접미사를 붙입니다. 접두사로는 막히지 않습니다 —
# 본문 매치가 앵커 없는 부분 문자열 검사라 원래 이름이 새 이름 안에 그대로 남습니다.
#
# ## 검사 규칙
#
# 대상 파일 본문에 등장하는 `*.sh` basename 리터럴 중, 아래 어디에도 해당하지 않으면 위반:
#   (1) `_zzfx.sh` 로 끝난다 — 규약을 지킨 fixture 이름입니다.
#   (2) 그 basename 의 파일이 이 스크립트 트리에 실제로 존재한다 — 실재하는 인프라 파일을
#       가리키는 참조이므로, 그 파일은 이미 자기 스텝이 커버합니다. 새로 구멍을 내지 않습니다.
#   (3) whitelist 에 있다 (아래 — **이유 주석 없는 등록 금지**).
#
# ## 검사 범위를 두 스위트로 한정하는 이유
#
# 인프라 전체로 넓히면 문서·주석의 일반 자리표시자까지 걸려 오탐이 대량 발생합니다.
# 폐포 판정이 주석을 본문과 구분하지 않는 구조 문제는 별건(FR closure-comment-literal-
# pollution)이고, 여기서는 규약을 실제로 지켜야 하는 두 파일만 봅니다.
set -u
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
rc=0

# 검사 대상. **이름을 여기에 리터럴로 적는 것은 의도적입니다** — 이 스크립트가 두 스위트의
# 참조 폐포 안에 들어가야 스위트가 바뀔 때 이 검사 스텝이 smoke 에서 함께 돕니다. 이름을
# 인자로 받아 호출부(오케스트레이터)에 두면 폐포가 끊겨, 정작 규약을 어긴 편집이 들어온
# 실행에서 이 검사가 스킵됩니다. 폐포가 넓어지는 대가는 없습니다 — 두 파일 모두 이미
# 자기 스텝의 폐포에 있어 새로 커버되는 이름이 늘지 않습니다.
#
# 이 스크립트 **자신도** 대상입니다. 여기에도 이름을 리터럴로 적을 이유가 계속 생기고
# (whitelist 항목의 이유 주석이 대표적입니다) 이 파일 역시 어떤 스텝의 폐포 구성원이라,
# 자기 규칙 밖에 두면 이 파일에 적은 평범한 이름이 그물에 구멍을 내면서 자기 검사에는
# 걸리지 않습니다. 현재 본문의 이름들은 규칙 (1)·(2) 로 통과합니다.
TARGETS=(
  "${SCRIPT_DIR}/test_smoke_common.sh"
  "${SCRIPT_DIR}/test_self_test_smoke.sh"
  "${SCRIPT_DIR}/check_fixture_name_convention.sh"
)

# 대상이 0건이면 **명시적으로 실패**합니다. 빈 배열은 `set -u` 아래 `"${TARGETS[@]}"` 가
# unbound 로 터져 우연히 rc≠0 이 되기는 했지만 그것은 사고이지 설계가 아니었습니다
# (bash 버전·가드 추가 어느 쪽으로든 조용한 통과로 뒤집힙니다). 대상이 없으면 이 검사는
# 무엇을 넣어도 통과하는 빈 껍데기이므로, 사고에 기대지 않고 여기서 판정합니다.
if (( ${#TARGETS[@]} == 0 )); then
  echo "  검사 대상이 0건입니다 — 무엇을 넣어도 통과하는 빈 껍데기가 됩니다" >&2
  rc=1
fi

# whitelist — 규약을 벗어나야 할 이유가 있는 이름만 둡니다.
# **각 항목에 이유를 주석으로 남기십시오.** 이유 없는 등록이 쌓이면 이 검사는 서서히
# 무력해지고, 그때는 실패하지 않는다는 사실 자체가 거짓 안심이 됩니다.
# (현재 비어 있습니다 — 두 스위트의 비-`_zzfx` 이름은 모두 규칙 (2) 로 통과합니다.)
WHITELIST=()

# 이 트리에 실재하는 basename 집합입니다. 개행 구분 문자열 하나로 두고 부분 문자열이 아니라
# **줄 단위 정확 일치**로 조회합니다 (`a_zzfx.sh` 가 `xa_zzfx.sh` 에 걸리면 안 됩니다).
existing="$(find "$SCRIPT_DIR" -type f -name '*.sh' 2>/dev/null | sed 's#.*/##' | sort -u)"
existing="
${existing}
"

in_whitelist() {
  local w
  for w in ${WHITELIST[@]+"${WHITELIST[@]}"}; do
    [[ "$w" == "$1" ]] && return 0
  done
  return 1
}

for t in ${TARGETS[@]+"${TARGETS[@]}"}; do
  # 대상이 사라졌으면 실패입니다. 조용히 건너뛰면 스위트 이름을 바꾸는 것만으로 이 검사가
  # 통과하는 빈 껍데기가 됩니다.
  if [[ ! -f "$t" ]]; then
    echo "  검사 대상이 없습니다: $t" >&2
    rc=1
    continue
  fi
  while IFS= read -r name; do
    [[ -n "$name" ]] || continue
    case "$name" in *_zzfx.sh) continue ;; esac
    case "$existing" in *"
${name}
"*) continue ;; esac
    in_whitelist "$name" && continue
    echo "  규약 위반: ${t##*/} 의 '${name}' — 실재하지 않는 이름인데 _zzfx 접미사가 없습니다" >&2
    rc=1
  done < <(grep -oE '[A-Za-z0-9_.-]+\.sh' "$t" 2>/dev/null | sort -u)
done

if [[ "$rc" -eq 0 ]]; then
  echo "  fixture 이름 규약 준수 (검사 대상 ${#TARGETS[@]}개)"
else
  echo "  fixture 이름에는 _zzfx 접미사를 붙이십시오 — 접두사는 부분 문자열 매치를 막지 못합니다." >&2
fi
exit $rc
